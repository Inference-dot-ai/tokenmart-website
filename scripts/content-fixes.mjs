/** Structural repairs for the two articles whose Markdown does not parse. */
export const STRUCTURAL = [
  // #48: a doubled heading marker renders the literal text "## Frequently...".
  [/^##\s+##\s+/gm, "## "],
  // #68: every H2 is wrapped in bold with the hashes inside the asterisks, so
  // none of them parses as a heading.
  [/^\*\*##\s*(.+?)\s*\*\*\s*$/gm, "## $1"],
  [/^\*\*###\s*(.+?)\s*\*\*\s*$/gm, "### $1"],
  // Generator scaffolding left as a visible bold label.
  [/^\*\*(Introduction|Conclusion)\*\*\s*$/gm, "## $1"],
];

/**
 * Apply every deterministic correction. Order matters: structure first so
 * headings parse, then model names, then unsupported commitments. Savings
 * claims are handled separately — see the note above.
 */
export function applyFixes(text) {
  let out = text;
  for (const [re, to] of STRUCTURAL) out = out.replace(re, to);
  for (const [re, to] of STALE_MODELS) out = out.replace(re, to);
  for (const [re, to] of UNSUPPORTED_CLAIMS) out = out.replace(re, to);
  return out.replace(/[ \t]{2,}/g, " ").replace(/ +([,.])/g, "$1");
}
