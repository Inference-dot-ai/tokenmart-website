// NOTE: savings claims are deliberately NOT handled by regex here.
//
// An earlier version capped every "up to N%" inside a sentence that mentioned
// the brand. It failed in both directions: it rewrote only 1 of 25 real
// over-claims (most offending sentences never name us explicitly), and it
// corrupted true statements — "Prompt Caching and the Batch API reduce base
// token costs by up to 90% and 50%, respectively" became "up to 15%", turning
// an accurate industry fact into a false one.
//
// Deciding whether a percentage is a provider-side fact or a promise we are
// making needs the surrounding argument, so those edits are produced by
// scripts/claim-edits.json (generated by a review pass) and applied verbatim.

